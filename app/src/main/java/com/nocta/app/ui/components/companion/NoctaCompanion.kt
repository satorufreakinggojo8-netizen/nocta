/**
 * Vela as a floating, borderless character cutout.
 *
 * The artwork is a genuinely transparent WebP (real alpha channel, generated by
 * `tools/cutout_vela.py`), so it renders straight onto Nocta's near-black
 * background: no card, no frame, no circle mask, no background plate. Only the
 * character's own pixels are drawn; `ContentScale.Fit` keeps the head and body
 * uncropped, and the image box is sized from the artwork's aspect ratio so a
 * tall portrait never turns into a squat thumbnail.
 *
 * The overlay itself is a transparent full-screen [BoxWithConstraints] that
 * does not consume touches; only the character's own bounds respond to drag
 * (clamped to the screen, so it can never be flung out of view) and tap (opens
 * the Coach). Dragging never moves the character over the top of the screen,
 * and its resting place is the bottom-trailing edge, matching the reference
 * composition.
 */
@Composable
fun NoctaCompanionOverlay(
    onClick: () -> Unit,
    modifier: Modifier = Modifier,
    characterHeight: Dp = 300.dp,
    portraitRes: Int = R.drawable.vela_companion
) {
    val painter = painterResource(id = portraitRes)
    val aspect = aspectRatioOf(painter)
    val characterWidth = characterHeight * aspect

    BoxWithConstraints(modifier = modifier.fillMaxSize()) {
        val density = LocalDensity.current
        val maxDragX = with(density) { (maxWidth - characterWidth).toPx() }.coerceAtLeast(0f)
        val maxDragY = with(density) { (maxHeight - characterHeight).toPx() }.coerceAtLeast(0f)
        var offset by remember { mutableStateOf(Offset.Zero) }

        Image(
            painter = painter,
            contentDescription = null,
            contentScale = ContentScale.Fit,
            alignment = Alignment.BottomCenter,
            modifier = Modifier
                .align(Alignment.BottomEnd)
                .offset { IntOffset(offset.x.roundToInt(), offset.y.roundToInt()) }
                .width(characterWidth)
                .height(characterHeight)
                .pointerInput(maxDragX, maxDragY) {
                    detectDragGestures { change, dragAmount ->
                        change.consume()
                        offset = Offset(
                            x = (offset.x + dragAmount.x).coerceIn(-maxDragX, 0f),
                            y = (offset.y + dragAmount.y).coerceIn(-maxDragY, 0f)
                        )
                    }
                }
                .clickable(
                    interactionSource = remember { MutableInteractionSource() },
                    // No ripple plate behind the artwork — the character is not a card.
                    indication = null
                ) { onClick() }
                .semantics {
                    role = Role.Button
                    contentDescription =
                        "Vela, your AI sleep coach. Double tap to open the coach."
                }
        )
    }
}

/**
 * Vela's portrait for headers and empty states — the same cutout artwork,
 * scaled down. No circle, border or glow plate: the transparency does the work.
 */
@Composable
fun VelaPortrait(
    modifier: Modifier = Modifier,
    height: Dp = 64.dp,
    portraitRes: Int = R.drawable.vela_portrait
) {
    val painter = painterResource(id = portraitRes)
    Image(
        painter = painter,
        contentDescription = "Vela",
        contentScale = ContentScale.Fit,
        modifier = modifier
            .height(height)
            .width(height * aspectRatioOf(painter))
    )
}

private fun aspectRatioOf(painter: Painter): Float {
    val size = painter.intrinsicSize
    return if (size.height > 0f && size.width > 0f) size.width / size.height else 0.35f
}
